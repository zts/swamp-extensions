/**
 * Builds review_page.ts from index.html. An extension ships only code and
 * text files, so the page goes out as a string in a module.
 *
 *   deno run --allow-read=. --allow-write=. review/build.ts
 *
 * Run it from the extension's folder after changing the page.
 *
 * @module
 */

/**
 * The module that carries the page. The page is a template literal, which
 * deno fmt leaves as it is, so swamp extension fmt and a rebuild agree.
 */
export function pageModule(html: string): string {
  const literal = html.replaceAll("\\", "\\\\").replaceAll("`", "\\`")
    .replaceAll("${", "\\${");
  return [
    "// Generated by review/build.ts from review/index.html. Do not edit:",
    "// change the page, then run deno run --allow-read=. --allow-write=. review/build.ts",
    "",
    "/** The review page. */",
    `export const PAGE_HTML = \`${literal}\`;`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  const html = await Deno.readTextFile(
    new URL("./index.html", import.meta.url),
  );
  await Deno.writeTextFile(
    new URL("../review_page.ts", import.meta.url),
    pageModule(html),
  );
}
